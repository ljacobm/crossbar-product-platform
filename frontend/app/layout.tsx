import type { Metadata, Viewport } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

// viewportFit: "cover" is required for env(safe-area-inset-*) to
// resolve to anything other than 0 -- without it, the customer
// catalog's fixed bottom bar can't account for iOS/Android gesture
// bars/home indicators at all (components/CatalogSubmitBar.tsx).
// App-wide (not catalog-specific) but purely additive and harmless
// elsewhere: safe-area-inset values are 0 on devices/browsers without
// a notch or gesture bar regardless of this setting.
export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  viewportFit: "cover",
};

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html
      lang="en"
      className={`${geistSans.variable} ${geistMono.variable} h-full antialiased`}
    >
      <body className="min-h-full flex flex-col">{children}</body>
    </html>
  );
}
